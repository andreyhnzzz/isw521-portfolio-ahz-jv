// Operadores en JavaScript

let a = 10;
let b = 3;

// Aritmeticos
console.log("Suma: " + (a + b));
console.log("Resta: " + (a - b));
console.log("Multiplicacion: " + (a * b));
console.log("Division: " + (a / b));
console.log("Modulo: " + (a % b));

// Comparacion
console.log("a > b: " + (a > b));
console.log("a < b: " + (a < b));
console.log("a == b: " + (a == b));
console.log("a != b: " + (a != b));

// Logicos
let x = true;
let y = false;

console.log("AND: " + (x && y));
console.log("OR: " + (x || y));
console.log("NOT x: " + (!x));
